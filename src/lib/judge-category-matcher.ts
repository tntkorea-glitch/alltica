/**
 * 외부 세부종목명 → 우리 등록 카테고리명 변환
 * @param divName 엑셀 등에서 온 세부종목명
 * @returns 매핑된 카테고리명 (실패 시 undefined)
 */
export function matchDivisionToCategory(divName: string): string | undefined {
  const normalized = divName.trim();

  // 1. 정확 매칭
  if (EXACT_ALIAS[normalized]) return EXACT_ALIAS[normalized];

  // 2. 대소문자/공백 무시 정확 매칭
  const lower = normalized.toLowerCase().replace(/\s+/g, "");
  for (const [alias, target] of Object.entries(EXACT_ALIAS)) {
    if (alias.toLowerCase().replace(/\s+/g, "") === lower) return target;
  }

  // 3. 키워드 패턴 매칭
  for (const rule of KEYWORD_RULES) {
    if (rule.test(normalized)) return rule.target;
  }

  return undefined;
}

/**
 * 카테고리 목록에서 세부종목명으로 ID 찾기
 * (matchDivisionToCategory 결과를 카테고리 이름 목록과 비교)
 */
export function resolveCategory(
  divName: string,
  categories: Array<{ id: string; name: string; major_category?: string }>
): string | undefined {
  // 직접 이름 매칭
  const direct = categories.find(
    (c) => c.name === divName || c.name.toLowerCase() === divName.toLowerCase()
  );
  if (direct) return direct.id;

  // 별칭 → 카테고리명 → ID
  const mappedName = matchDivisionToCategory(divName);
  if (!mappedName) return undefined;

  const found = categories.find(
    (c) => c.name === mappedName || c.name.toLowerCase() === mappedName.toLowerCase()
  );
  return found?.id;
}
